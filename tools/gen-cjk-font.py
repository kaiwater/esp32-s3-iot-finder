#!/usr/bin/env python3
"""Generate 12x12 CJK and GBK->Unicode tables from Noto Sans CJK SC.

The generated bitmap is a derived work of Noto Sans CJK SC (SIL Open Font
License 1.1).  The font file itself is not committed; see docs/OFL.txt.

Usage:
    python3 tools/gen-cjk-font.py NotoSansCJKsc-Regular.otf main
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W = H = 12
GLYPH_BYTES = (W + 7) // 8 * H  # 24 bytes
HAN_FIRST, HAN_LAST = 0x4E00, 0x9FFF
PUNCT_FIRST, PUNCT_LAST = 0x3000, 0x303F
FULL_FIRST, FULL_LAST = 0xFF00, 0xFFEF


def glyph(font, cp):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    try:
        d.text((0, 0), chr(cp), font=font, fill=255, anchor="lt")
    except Exception:
        return bytes(GLYPH_BYTES)
    px = img.load()
    out = bytearray(GLYPH_BYTES)
    for y in range(H):
        bits = 0
        for x in range(W):
            if px[x, y] >= 80:
                bits |= 0x8000 >> x
        off = y * 2
        out[off] = bits >> 8
        out[off + 1] = bits & 0xFF
    return bytes(out)


def emit_array(f, name, first, last, font):
    f.write(f"static const uint8_t {name}[{last - first + 1}][{GLYPH_BYTES}] = {{\n")
    for cp in range(first, last + 1):
        g = glyph(font, cp)
        f.write("{" + ",".join(f"0x{b:02X}" for b in g) + "},\n")
    f.write("};\n\n")


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    font_path = sys.argv[1]
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    font = ImageFont.truetype(font_path, W)

    with open(outdir / "cjk_font_data.h", "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen-cjk-font.py.  Noto Sans CJK SC, OFL-1.1. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define CJK_W {W}\n#define CJK_H {H}\n")
        f.write(f"#define CJK_GLYPH_BYTES {GLYPH_BYTES}\n")
        f.write(f"#define CJK_HAN_FIRST 0x{HAN_FIRST:X}\n#define CJK_HAN_COUNT {HAN_LAST - HAN_FIRST + 1}\n")
        f.write(f"#define CJK_PUNCT_FIRST 0x{PUNCT_FIRST:X}\n#define CJK_PUNCT_COUNT {PUNCT_LAST - PUNCT_FIRST + 1}\n")
        f.write(f"#define CJK_FULL_FIRST 0x{FULL_FIRST:X}\n#define CJK_FULL_COUNT {FULL_LAST - FULL_FIRST + 1}\n\n")
        emit_array(f, "cjk_han", HAN_FIRST, HAN_LAST, font)
        emit_array(f, "cjk_punct", PUNCT_FIRST, PUNCT_LAST, font)
        emit_array(f, "cjk_full", FULL_FIRST, FULL_LAST, font)

    with open(outdir / "gbk_table.h", "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen-cjk-font.py from Python's GBK codec. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define GBK_LEAD_MIN 0x81\n#define GBK_LEAD_COUNT 126\n")
        f.write("#define GBK_TRAIL_MIN 0x40\n#define GBK_TRAIL_COUNT 190\n\n")
        f.write("static const uint16_t gbk_to_unicode[GBK_LEAD_COUNT][GBK_TRAIL_COUNT] = {\n")
        for lead in range(0x81, 0xFF):
            row = []
            for trail in range(0x40, 0xFF):
                if trail == 0x7F:
                    continue
                try:
                    ch = bytes((lead, trail)).decode("gbk")
                    cp = ord(ch) if len(ch) == 1 else 0xFFFF
                    row.append(cp if cp <= 0xFFFF else 0xFFFF)
                except UnicodeDecodeError:
                    row.append(0xFFFF)
            f.write("{" + ",".join(f"0x{v:04X}" for v in row) + "},\n")
        f.write("};\n")

    print("wrote", outdir / "cjk_font_data.h", "and", outdir / "gbk_table.h")


if __name__ == "__main__":
    main()
